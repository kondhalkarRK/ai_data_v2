_ENGINE_CODES = {"P": "Petrol", "D": "Diesel", "H": "Hybrid", "E": "Electric"}


@dataclass(frozen=True, slots=True)
class Variant:
    engine_type: str
    capacity: float | None
    price_lakh: float
    start: str | None = None
    end: str | None = None
    share: float | dict[int, float] = 1.0


@dataclass(frozen=True, slots=True)
class ModelSpec:
    make: str
    model: str
    car_type: str
    windows: tuple[tuple[str | None, str | None], ...]
    volume: dict[int, float]
    variants: tuple[Variant, ...]
    channel: str | None = None
    fleet: float = 0.0
    price_steps: tuple[tuple[str, float], ...] = field(default_factory=tuple)

    @property
    def launch(self) -> date:
        start = self.windows[0][0]
        return month_start(start) if start else DATA_START

    @property
    def launched_in_window(self) -> bool:
        return self.windows[0][0] is not None


def month_start(value: str) -> date:
    year, month = value.split("-")
    return date(int(year), int(month), 1)


def month_end(value: str) -> date:
    start = month_start(value)
    nxt = date(start.year + (start.month == 12), start.month % 12 + 1, 1)
    return date.fromordinal(nxt.toordinal() - 1)


def V(  # noqa: N802 - compact catalogue notation
    code: str,
    capacity: float | None,
    price: float,
    start: str | None = None,
    end: str | None = None,
    share: float | dict[int, float] = 1.0,
) -> Variant:
    engine = _ENGINE_CODES[code]
    return Variant(engine, None if engine == "Electric" else capacity, price, start, end, share)


def M(  # noqa: N802 - compact catalogue notation
    make: str,
    model: str,
    car_type: str,
    start: str | None,
    end: str | None,
    volume: dict[int, float],
    *variants: Variant,
    windows: tuple[tuple[str | None, str | None], ...] | None = None,
    channel: str | None = None,
    fleet: float = 0.0,
    price_steps: tuple[tuple[str, float], ...] = (),
) -> ModelSpec:
    return ModelSpec(
        make=make,
        model=model,
        car_type=car_type,
        windows=windows or ((start, end),),
        volume=volume,
        variants=variants,
        channel=channel,
        fleet=fleet,
        price_steps=price_steps,
    )


