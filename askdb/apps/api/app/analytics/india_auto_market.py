"""Indian passenger-vehicle market knowledge used by the realistic automotive dataset.

Every number here is a modelled approximation of the public Indian PV market
(SIAM-style monthly volumes, ex-showroom prices, launch calendars). It is used to
shape synthetic data; it is not OEM data. See docs/automotive-india-market-dataset.md.

Conventions
-----------
* ``volume``: typical national monthly units by calendar year (mid-year level).
* ``price``: average ex-showroom price in INR lakh at 2024 price levels for that
  powertrain; other years are derived from the price index.
* windows: ``("YYYY-MM", "YYYY-MM" | None)``; start is the first month on sale,
  end is the last month on sale (inclusive). ``None`` start means before 2015.
"""

